const { contextBridge, ipcRenderer } = require('electron');

const call = (ch, ...a) => ipcRenderer.invoke(ch, ...a);
const on = (ch, fn) => ipcRenderer.on(ch, (_e, d) => fn(d));

contextBridge.exposeInMainWorld('hn', {
  board: () => call('board:get'),
  settings: () => call('settings:get'),
  setSettings: p => call('settings:set', p),
  scan: () => call('scan'),
  runAI: force => call('ai:run', force),
  aiState: () => call('ai:state'),
  setItem: (id, p) => call('item:set', id, p),
  setDl: (id, date, p) => call('dl:set', id, date, p),
  addDl: (id, d) => call('dl:add', id, d),
  removeMyDl: (id, date) => call('dl:removeMine', id, date),
  addManual: m => call('manual:add', m),
  removeManual: id => call('manual:remove', id),
  assignSession: (sid, id) => call('session:assign', sid, id),
  openPath: p => call('open:path', p),
  reveal: p => call('open:reveal', p),
  openCode: p => call('open:code', p),
  resume: (sid, cwd) => call('open:resume', sid, cwd),
  openUrl: u => call('open:url', u),
  copy: t => call('copy', t),
  openData: () => call('open:data'),
  pin: v => call('win:pin', v),
  mini: v => call('win:mini', v),
  showMain: () => call('win:main'),
  selectInMain: id => call('win:select', id),
  testBrief: () => call('brief:test'),
  dismissBrief: keep => call('brief:dismiss', keep),
  idleStatus: () => call('idle:status'),
  calStatus: () => call('cal:status'),
  calSync: () => call('cal:sync'),
  calConnect: () => call('cal:connect'),
  calDisconnect: () => call('cal:disconnect'),
  calOpenIcs: () => call('cal:openIcs'),
  activityState: () => call('activity:state'),
  activityClear: () => call('activity:clear'),
  activityToday: () => call('activity:today'),
  info: () => call('app:info'),
  calScriptCode: () => call('cal:scriptCode'),
  calScriptConnect: url => call('cal:scriptConnect', url),
  calScriptOff: () => call('cal:scriptOff'),
  calImportClient: () => call('cal:importClient'),
  addFolders: () => call('folders:add'),
  setFolder: (p, patch) => call('folders:set', p, patch),
  removeFolder: p => call('folders:remove', p),
  foundRescan: () => call('found:rescan'),
  setFound: (keys, patch) => call('found:set', keys, patch),
  foundAI: () => call('found:ai'),
  applyChanges: (id, ch) => call('item:apply', id, ch),
  nlAI: (text, cur) => call('nl:ai', text, cur),
  agentInfo: () => call('agent:info'),
  agentTest: agent => call('agent:test', agent),
  addRoots: () => call('roots:add'),
  on,
});
